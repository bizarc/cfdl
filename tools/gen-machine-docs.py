        f"- [IR schema]({SITE}/docs/specification/ir-schema) — JSON Schema at",
        f"  [{SITE}/schemas/CFDL_v0_1_IR.schema.json]({SITE}/schemas/CFDL_v0_1_IR.schema.json)",
