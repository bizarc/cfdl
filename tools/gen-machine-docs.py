        "",
        "## Machine bundle",
        "",
        f"- [Machine docs bundle]({SITE}/machine/cfdl-machine-docs.md): the language",
        "  spec, full EBNF grammar, expression environment, IR and results schemas,",
        "  pack interface, diagnostics catalog, controlled-English authoring contract,",
        "  glossary, terminology register, and pack rosters, in one versioned document",
        f"- [Diagnostics repair catalog]({SITE}/machine/diagnostics-repairs.md): per",
        "  diagnostic code, a minimal failing example and (where recorded) its minimal",
        "  compile-verified fix",
        f"- [Valid examples corpus]({SITE}/machine/valid-examples.md): every golden",
        "  fixture model — single-purpose, compiling, byte-asserted in CI; what right",
        "  looks like",
        f"- [llms-full.txt]({SITE}/llms-full.txt): the bundle plus every course",
